function detectLocale() {
  try {
    const stored = localStorage.getItem(STORAGE_KEYS.locale)
    if (stored === 'en' || stored === 'zh') return stored
  } catch {
    /* storage unavailable */
  }
  return String(navigator.language || '').toLowerCase().startsWith('en') ? 'en' : 'zh'
}

export const locale = ref(detectLocale())

export function setLocale(value, { persist = true } = {}) {
  const next = value === 'en' ? 'en' : 'zh'
  locale.value = next
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN'
  if (persist) {
    try {
      localStorage.setItem(STORAGE_KEYS.locale, next)
    } catch {
      /* storage unavailable */
    }
  }
}

export function autoLocale() {
  setLocale(detectLocale())
}

export function t(key, params = {}) {
  const table = messages[locale.value] || messages.zh
  let text = table[key] ?? messages.zh[key] ?? key
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

export function useI18n() {
  return { locale, t, setLocale }
}
